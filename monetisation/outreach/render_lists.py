def esc(s: str) -> str:
    return s.replace("|", "/").replace("\n", " ").strip()


def render_table(rows, code):
    out = ["| ID | Name (zh-TW / English) | Type | Why it fits; lead with | Route | Compliance flags | Pri | Status |",
           "| :-- | :-- | :-- | :-- | :-- | :-- | :-- | :-- |"]
    for r in rows:
        route = ROUTE_CODES.get(r["contact_route"], "see CSV")
        name = f"**{esc(r['name_zh'])}**<br>{esc(r['name_en'])}<br>conf: {r['existence_confidence']}"
        if r["also_in"]:
            name += f"; also: {r['also_in']}"
        typ = f"{r['type']}<br>{esc(r['subtype'])}"
        why = f"{esc(r['why_it_fits'])}<br>**Lead:** {esc(r['lead_with'])}"
        flags = esc(r["compliance_flags"])
        if r["group_note"]:
            flags += f"<br>**Group:** {esc(r['group_note'])}"
        out.append(f"| {r['id']} | {name} | {typ} | {why} | {route} | {flags} | {r['priority']} | {r['status']} |")
    return "\n".join(out)


def render_list(key):
    meta = LISTS[key]
    rows = read(HERE / f"{meta['file']}.csv")
    parts = [HEAD.format(title=meta["title"], zh=meta["zh"], file=meta["file"], showroom=meta["showroom"], offer=meta["offer"]),
             shortfall_text(key, rows), "", LEGEND, NOTES[key], "## The list", "", render_table(rows, meta["code"]), "",
             "_End of generated page. Columns that are only in the CSV: `basis`, `warm_route_note`, `verify`, `verified_on`, `template`, full `contact_route`._", ""]
    return "\n".join(parts)


def counts_block():
    allrows = {k: read(HERE / f"{m['file']}.csv") for k, m in LISTS.items()}
    lines = ["| List | Rows | P1 | P2 | P3 | HOLD | SKIP | Actionable (P1 to P3) | Against the target of 50 |",
             "| :-- | --: | --: | --: | --: | --: | --: | --: | :-- |"]
    for k, m in LISTS.items():
        rows = allrows[k]
        c, act = counts(rows)
        verdict = "target reached" if len(rows) >= TARGET and act >= TARGET else (
            f"{TARGET - len(rows)} rows short; {TARGET - act} actionable short" if len(rows) < TARGET else
            f"{TARGET - act} actionable short")
        lines.append(f"| [{m['title']}]({m['file']}.md) | {len(rows)} | {c['P1']} | {c['P2']} | {c['P3']} | {c['HOLD']} | {c['SKIP']} | {act} | {verdict} |")
    uniq = {}
    for k, rows in allrows.items():
        for r in rows:
            uniq.setdefault(r["name_zh"], set()).add(LISTS[k]["code"])
    multi = sum(1 for v in uniq.values() if len(v) > 1)
    total_rows = sum(len(v) for v in allrows.values())
    lines.append("")
    lines.append(f"{total_rows} rows in total, {len(uniq)} distinct entities ({multi} appear in more than one list). "
                 f"Counted by zh-TW name; one open thread per entity applies across lists.")
    return "\n".join(lines)


def replace_block(text, name, new):
    b, e = f"<!-- BEGIN GENERATED:{name} -->", f"<!-- END GENERATED:{name} -->"
    i, j = text.find(b), text.find(e)
    if i < 0 or j < 0:
        raise SystemExit(f"README.md is missing the {name} markers")
    return text[: i + len(b)] + "\n" + new + "\n" + text[j:]


DNC_COLS = ["entity_name", "name_en", "list_id", "group_note", "reason", "reason_detail", "date_added", "added_by", "removal_requires"]
DNC_FILE = "do-not-contact-template.csv"


def dnc_text():
    """Seed the do-not-contact sheet from the HOLD and SKIP rows of the three lists."""
    import io
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(DNC_COLS)
    for key, meta in LISTS.items():
        for r in read(HERE / f"{meta['file']}.csv"):
            if r["priority"] not in ("HOLD", "SKIP"):
                continue
            reason = "declined_category" if r["priority"] == "SKIP" else "hold_lawyer"
            detail = ("Property sales, mortgage and investment adjacency (decline-list C20; Ground rule 6)" if r["priority"] == "SKIP"
                      else "Rental platform: decline unless a lawyer clears it (decline-list C29; bible 9.2)")
            w.writerow([r["name_zh"], r["name_en"], r["id"], r["group_note"], reason, detail, "2026-10-12",
                        "drafted by Claude from the list; confirm", "both of you"])
    return buf.getvalue()


def main():
    check = "--check" in sys.argv
    stale = []
    for key, meta in LISTS.items():
        path = HERE / f"{meta['file']}.md"
        new = render_list(key)
        old = path.read_text(encoding="utf-8") if path.exists() else ""
        if old != new:
            stale.append(path.name)
            if not check:
                path.write_text(new, encoding="utf-8")
    dnc = HERE / DNC_FILE
    new_dnc = dnc_text()
    old_dnc = dnc.read_text(encoding="utf-8") if dnc.exists() else ""
    if old_dnc != new_dnc:
        stale.append(DNC_FILE)
        if not check:
            dnc.write_text(new_dnc, encoding="utf-8")
    readme = HERE / "README.md"
    if readme.exists():
        old = readme.read_text(encoding="utf-8")
        new = replace_block(old, "counts", counts_block())
        if old != new:
            stale.append(readme.name)
            if not check:
                readme.write_text(new, encoding="utf-8")
    if check:
        if stale:
            print("STALE: " + ", ".join(stale) + " (run render_lists.py)")
            return 1
        print("generated files are up to date")
        return 0
    print("rewrote: " + (", ".join(stale) if stale else "nothing (already up to date)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
