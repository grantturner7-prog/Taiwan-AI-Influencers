def read(path: Path):
    with path.open(encoding="utf-8", newline="") as fh:
        return list(csv.DictReader(fh))


def counts(rows):
    c = Counter(r["priority"] for r in rows)
    actionable = sum(c[p] for p in ("P1", "P2", "P3"))
    return c, actionable


def shortfall_text(key, rows):
    n = len(rows)
    c, act = counts(rows)
    pri = ", ".join(f"{p} {c[p]}" for p in PRI_ORDER if c[p])
    out = [f"**Count: {n} rows ({pri}). Actionable rows (P1 to P3): {act}.**"]
    if n >= TARGET and act >= TARGET:
        out.append(f"The target of {TARGET} is reached with entities I am confident exist, but see the weak point below.")
    elif n >= TARGET:
        out.append(f"The target of {TARGET} rows is reached, but only {act} are actionable ({c['HOLD']} HOLD and {c['SKIP']} SKIP rows are listed so that nobody contacts them by mistake). **Shortfall: {TARGET - act} actionable rows.**")
    else:
        out.append(f"**Shortfall: {TARGET - n} rows short of {TARGET}** ({TARGET - act} short of {TARGET} actionable rows). I did not pad the list with guesses.")
    return "\n".join(out)


